export enum AnchorLocation {
  Cover, // Stretches directly over the target element
  TopLeft, // Grows down-right from element's Top-Left corner
  TopRight, // Grows down-left from element's Top-Right corner
  BottomLeft, // Grows up-right from element's Bottom-Left corner
  BottomRight, // Grows up-left from element's Bottom-Right corner
}
